/** C/N0 is carrier-to-noise density, in dB-Hz, not received power in dBm. */
export interface Satellite {
  id: string;
  constellation: 'GPS' | 'GLONASS' | 'Galileo' | 'BeiDou' | 'QZSS' | 'SBAS' | 'NavIC' | 'Unknown' | (string & {});
  azimuth: number;
  elevation: number;
  cn0?: number | null;
  used?: boolean;
  signal?: string;
}
export type Fix = 'unknown' | 'none' | '2d' | '3d';
export interface SkyFrame { satellites: Satellite[]; fix?: Fix }
export interface SkyOptions {
  compass: boolean; grid: boolean; labels: boolean;
  signalColors: boolean; constellationColors: boolean;
  showLock: boolean; usedOnly: boolean;
  minElevation: number;
  /** Bearing at the top of the plot, clockwise from north. Default 0 = north-up. */
  rotation: number;
  tooltips: boolean;
}
export const defaultOptions: Readonly<SkyOptions> = Object.freeze({
  compass:true, grid:true, labels:true, signalColors:true, constellationColors:true,
  showLock:true, usedOnly:false, minElevation:0, rotation:0, tooltips:true,
});
interface WasmApi extends WebAssembly.Exports {
  memory: WebAssembly.Memory;
  alloc(n:number):number;
  dealloc(p:number,n:number):void;
  render_json(p:number,n:number):bigint;
}
export interface Renderer { render(frame:SkyFrame, options:SkyOptions):string }
/** Instantiate an isolated WASM renderer. Pass a URL for custom asset hosting. */
export async function loadRenderer(url: string | URL = new URL('./wasm_satsview.wasm', import.meta.url)): Promise<Renderer> {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`WASM load failed: HTTP ${response.status}`);
  const { instance } = await WebAssembly.instantiate(await response.arrayBuffer(), {});
  const api = instance.exports as WasmApi;
  const encoder = new TextEncoder(), decoder = new TextDecoder();
  return { render(frame, options) {
    const { tooltips: _tooltips, ...renderOptions } = options;
    const input = encoder.encode(JSON.stringify({frame,options:renderOptions}));
    if (input.length > 1_048_576) throw new Error('Frame exceeds 1 MiB');
    const p = api.alloc(input.length);
    let out = 0, len = 0;
    try {
      new Uint8Array(api.memory.buffer, p, input.length).set(input);
      const packed = api.render_json(p,input.length);
      out = Number(packed & 0xffffffffn); len = Number(packed >> 32n);
      const result = JSON.parse(decoder.decode(new Uint8Array(api.memory.buffer,out,len)));
      if (result.error) throw new TypeError(result.error);
      return result.svg;
    } finally {
      api.dealloc(p,input.length);
      if (out) api.dealloc(out,len);
    }
  }};
}
/** Reusable responsive control. Each update is a complete satellite snapshot. */
export class SkyView {
  private options: SkyOptions;
  private frame: SkyFrame = {satellites:[],fix:'unknown'};
  private root: HTMLDivElement;
  private plot: HTMLDivElement;
  private tooltip: HTMLDivElement;
  private disposed = false;
  constructor(host:HTMLElement, private renderer:Renderer, options:Partial<SkyOptions> = {}) {
    this.options = {...defaultOptions,...options};
    this.root = document.createElement('div');
    this.root.className = 'wasm-satsview';
    this.root.style.cssText = 'position:relative;width:100%;font-family:system-ui,sans-serif;color:#d9e5f4;background:#0b1626;border-radius:16px;';
    this.plot = document.createElement('div');
    this.tooltip = document.createElement('div');
    this.tooltip.role = 'status'; this.tooltip.hidden = true;
    this.tooltip.style.cssText = 'position:absolute;left:12px;right:12px;bottom:8px;padding:10px 14px;border:1px solid #617791;border-radius:8px;background:#14263c;font-size:13px;pointer-events:none;z-index:1;white-space:pre-line;';
    this.root.append(this.plot,this.tooltip);
    this.paint(this.frame,this.options);
    host.append(this.root);
    this.plot.addEventListener('pointerover',this.showDetails);
    this.plot.addEventListener('focusin',this.showDetails);
    this.plot.addEventListener('pointerout',this.hideDetails);
    this.plot.addEventListener('focusout',this.hideDetails);
    this.plot.addEventListener('keydown',this.onKey);
  }
  private paint(frame:SkyFrame,options:SkyOptions) {
    const svg = this.renderer.render(frame,options);
    this.plot.innerHTML = svg; // Only escaped SVG generated by the trusted WASM renderer.
    const node = this.plot.querySelector('svg')!;
    node.style.cssText = 'display:block;width:100%;height:auto;';
    if (!options.tooltips) this.plot.querySelectorAll('title').forEach(n=>n.remove());
    this.tooltip.hidden = true;
  }
  update(frame:SkyFrame):void {
    this.assertLive();
    const snapshot = structuredClone(frame);
    this.paint(snapshot,this.options);
    this.frame = snapshot;
  }
  setOptions(options:Partial<SkyOptions>):void {
    this.assertLive();
    const next = {...this.options,...options};
    this.paint(this.frame,next); this.options = next;
  }
  private assertLive() { if (this.disposed) throw new Error('SkyView has been destroyed'); }
  private showDetails = (event:Event) => {
    if (!this.options.tooltips) return;
    const marker = (event.target as Element).closest('[data-satellite]');
    if (!marker) return;
    const sat = this.frame.satellites[Number(marker.getAttribute('data-satellite'))];
    this.tooltip.textContent = `${sat.constellation} · ${sat.id}${sat.signal ? ` · ${sat.signal}` : ''}\nAzimuth ${sat.azimuth.toFixed(1)}° · Elevation ${sat.elevation.toFixed(1)}° · C/N0 ${sat.cn0 == null ? 'unknown' : `${sat.cn0.toFixed(1)} dB-Hz`} · ${sat.used ? 'Used in fix' : 'Not used in fix'}`;
    this.tooltip.hidden = false;
  };
  private hideDetails = (event:Event) => {
    const related = (event as MouseEvent).relatedTarget;
    const marker = (event.target as Element).closest('[data-satellite]');
    if (related instanceof Node && marker?.contains(related)) return;
    this.tooltip.hidden = true;
  };
  private onKey = (event:KeyboardEvent) => { if(event.key==='Escape') this.tooltip.hidden=true; };
  destroy():void {
    if (this.disposed) return;
    this.plot.removeEventListener('pointerover',this.showDetails);
    this.plot.removeEventListener('focusin',this.showDetails);
    this.plot.removeEventListener('pointerout',this.hideDetails);
    this.plot.removeEventListener('focusout',this.hideDetails);
    this.plot.removeEventListener('keydown',this.onKey);
    this.root.remove(); this.disposed=true;
  }
}
